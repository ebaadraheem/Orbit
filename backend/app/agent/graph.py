"""
The agent graph. First router node, then prepare node, then act node, then back to router. 
The router is the only node that calls the LLM; the rest of the graph is pure Python.
The prepare node runs once per tool call, generates all the ids for that step, and emits the "running" events. 
The act node runs the tool, emits the "done" events,
"""

from __future__ import annotations

from typing import Any

from langchain_core.messages import AIMessage, SystemMessage, ToolMessage
from langgraph.config import get_stream_writer
from langgraph.graph import END, START, StateGraph
from langgraph.types import interrupt

from .. import db, events
from ..events import new_id
from ..permissions import classify
from .llm import get_llm
from .state import AgentState
from .tools.registry import ACTIVITY_TYPE, ALL_TOOLS, TOOLS_BY_NAME

SYSTEM_PROMPT = """You are Orbit, a private assistant that lives on the user's computer.

You can answer directly, or use tools to look at files, open applications,
read the screen state, run commands, or take notes. Use tools only when the
request actually needs them — plain questions get plain answers.

When you do use tools:
- Make one tool call at a time and wait for its result before deciding the next step.
- Keep your final reply short, conversational, and free of technical detail
  the user didn't ask for (no file paths dumped verbatim, no step-by-step
  narration of what you did — the interface already shows that).
- Never mention "chain of thought", planning, or your own reasoning process
  in your reply. State conclusions, not deliberation.
- If something failed, say what failed and what you'd try next, plainly.
"""


def _describe_call(name: str, args: dict[str, Any]) -> tuple[str, str | None]:
    """A short user-facing label + optional detail for a tool call, built
    from the call itself — never from the model's own freeform text. This
    is what keeps the task panel free of exposed reasoning: the label is
    generated by code, not sampled from the LLM."""
    if name == "search_files":
        return f"Searching for \"{args.get('query', '')}\"", args.get("root")
    if name == "read_text_file":
        path = str(args.get("path", ""))
        return f"Reading {path.split('/')[-1].split(chr(92))[-1]}", None
    if name == "open_file":
        path = str(args.get("path", ""))
        return f"Opening {path.split('/')[-1].split(chr(92))[-1]}", None
    if name == "move_to_trash":
        count = len(args.get("paths", []))
        return (
            f"Moving {count} file{'s' if count != 1 else ''} to the Recycle Bin",
            None,
        )
    if name == "launch_app":
        return f"Launching {args.get('name', 'application')}", None
    if name == "list_running_apps":
        return "Checking open applications", None
    if name == "run_command":
        return "Running a command", str(args.get("command", ""))
    if name == "append_note":
        return "Writing to your notes", None
    return f"Running {name}", None


def _last_tool_calling_message(messages: list[Any]) -> AIMessage:
    for msg in reversed(messages):
        if isinstance(msg, AIMessage) and msg.tool_calls:
            return msg
    raise RuntimeError("act_node reached with no pending tool calls")


def router_node(state: AgentState) -> dict[str, Any]:
    """The router node is the entry point for the agent. It takes the initial system prompt + the conversation so far and produces a single AIMessage with a batch of tool calls (or none, if the model is done). The
    graph then runs the tool calls, appends the result to the conversation, and loops back to the router to determine the next step. The router is the only node that calls the LLM;
    the rest of the graph is pure Python."""
    llm = get_llm().bind_tools(ALL_TOOLS)
    response = llm.invoke([SystemMessage(content=SYSTEM_PROMPT), *state["messages"]])
    # Reset here for every new LLM call, so the model doesn't see its own previous tool call results
    return {"messages": [response], "step_index": 0}


def route_after_router(state: AgentState) -> str:
    last = state["messages"][-1]
    if isinstance(last, AIMessage) and last.tool_calls:
        return "prepare"
    return END


def prepare_node(state: AgentState) -> dict[str, Any]:
    """Runs exactly once per step, never crosses an interrupt. Generates
    every id this step needs and emits the 'running' events, so `act_node`
    can be replayed safely without anything shifting under it."""
    writer = get_stream_writer()
    ai_message = _last_tool_calling_message(state["messages"])
    idx = state.get("step_index", 0)
    call = ai_message.tool_calls[idx]
    name, args, call_id = call["name"], call["args"], call["id"]

    task_id = state.get("task_id")
    if not task_id:
        task_id = new_id("task")
        title = state.get("task_title") or "Working on it"
        writer(events.task_started(task_id, title))

    label, detail = _describe_call(name, args)
    step_id = new_id("step")
    activity_kind = ACTIVITY_TYPE.get(name, "system")

    writer(events.task_step(task_id, step_id, label, "running", detail))
    writer(events.activity(new_id("act"), activity_kind, label, "running", detail))

    return {
        "task_id": task_id,
        "current_call": {
            "name": name,
            "args": args,
            "call_id": call_id,
            "step_id": step_id,
            "label": label,
            "detail": detail,
            "activity_kind": activity_kind,
        },
    }


def act_node(state: AgentState) -> dict[str, Any]:
    """May pause here (`interrupt`). Everything above the `interrupt()` call
    in this function is pure — no writer calls, no id generation — so it is
    safe for LangGraph to re-run it on resume."""
    writer = get_stream_writer()
    call = state["current_call"]
    name, args, call_id = call["name"], call["args"], call["call_id"]
    step_id, label, activity_kind = (
        call["step_id"],
        call["label"],
        call["activity_kind"],
    )
    task_id = state["task_id"]

    settings = db.get_settings()
    verdict = classify(name, args, settings)

    if verdict.decision == "ask":
        decision = interrupt(
            {
                "tool": name,
                "args": args,
                "risk": verdict.risk,
                "title": verdict.title,
                "summary": verdict.summary,
                "confirm_label": verdict.confirm_label,
                "literal": verdict.literal,
                "consequence": verdict.consequence,
                "task_id": task_id,
                "step_id": step_id,
            }
        )
        granted = bool(decision.get("granted"))
        if not granted:
            writer(events.task_step(task_id, step_id, label, "skipped"))
            writer(events.activity(new_id("act"), activity_kind, label, "failed"))
            result_text = "The user declined this action."
        else:
            result_text = _run_tool(name, args)
            writer(events.task_step(task_id, step_id, label, "completed"))
            writer(events.activity(new_id("act"), activity_kind, label, "done"))
    elif verdict.decision == "deny":
        writer(events.task_step(task_id, step_id, label, "failed", verdict.summary))
        writer(events.activity(new_id("act"), activity_kind, label, "failed"))
        result_text = f"Not allowed: {verdict.summary}"
    else:
        result_text = _run_tool(name, args)
        writer(events.task_step(task_id, step_id, label, "completed"))
        writer(events.activity(new_id("act"), activity_kind, label, "done"))

    idx = state.get("step_index", 0)
    return {
        "messages": [ToolMessage(content=result_text, tool_call_id=call_id)],
        "step_index": idx + 1,
        "current_call": None,
    }


def _run_tool(name: str, args: dict[str, Any]) -> str:
    tool = TOOLS_BY_NAME[name]
    try:
        result = tool.invoke(args)
        return str(result)
    except (
        Exception
    ) as exc:  # noqa: BLE001 — surfaced to the model as a tool result, not a crash
        return f"Error running {name}: {exc}"


def route_after_act(state: AgentState) -> str:
    ai_message = _last_tool_calling_message(state["messages"])
    if state.get("step_index", 0) < len(ai_message.tool_calls):
        return "prepare"
    return "router"


def build_graph(checkpointer):
    graph = StateGraph(AgentState)
    graph.add_node("router", router_node)
    graph.add_node("prepare", prepare_node)
    graph.add_node("act", act_node)
    graph.add_edge(START, "router")
    graph.add_conditional_edges(
        "router", route_after_router, {"prepare": "prepare", END: END}
    )
    graph.add_edge("prepare", "act")
    graph.add_conditional_edges(
        "act", route_after_act, {"prepare": "prepare", "router": "router"}
    )
    return graph.compile(checkpointer=checkpointer)
